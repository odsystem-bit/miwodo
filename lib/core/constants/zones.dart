  /// Retourne la liste des villes pour un pays (par ID ISO)
  static List<String> villesParPays(String paysId) {
    final villes = paysVillesZones[paysId];
    if (villes == null) return lome; // fallback Lomé
    return villes.keys.toList();
  }

  /// Retourne la liste des zones/quartiers pour une ville d'un pays
  static List<String> zonesParVille(String paysId, String ville) {
    final villes = paysVillesZones[paysId];
    if (villes == null) return lome;
    return villes[ville] ?? [ville];
  }

  /// Retourne toutes les zones pour un pays (toutes villes confondues)
  static List<String> toutesLesZones(String paysId) {
    final villes = paysVillesZones[paysId];
    if (villes == null) return lome;
    final all = <String>[];
    for (final entry in villes.entries) {
      for (final zone in entry.value) {
        all.add('${entry.key} - $zone');
      }
    }
    return all;
  }
